"""Writes paper/response/numbers_ru.tex: the macros of paper/numbers.tex and numbers_validation.tex with decimal
commas (Russian typography) for the response to the referee comments."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
out = ["% Auto-generated by scripts/08_response_numbers.py -- do not edit by hand.", r"\makeatletter",
       r"\newcommand{\val}[1]{\@ifundefined{val@#1}{??#1??}{\csname val@#1\endcsname}}", r"\makeatother"]
pat = re.compile(r"^\\expandafter\\def\\csname val@(\w+)\\endcsname\{(.*)\}$")
for f in ("numbers.tex", "numbers_validation.tex"):
    for line in (ROOT / "paper" / f).read_text().splitlines():
        m = pat.match(line)
        if not m:
            continue
        key, v = m.groups()
        v = v.replace("{,}", "\\,")  # thousands separators: thin space in Russian typography
        v = re.sub(r"(\d)\.(\d)", r"\1{,}\2", v)
        v = re.sub(r"^-(?=\d)", r"\\textminus{}", v)
        out.append("\\expandafter\\def\\csname val@" + key + "\\endcsname{" + v + "}")
(ROOT / "paper" / "response" / "numbers_ru.tex").write_text("\n".join(out) + "\n")
print(len(out) - 4, "macros")
